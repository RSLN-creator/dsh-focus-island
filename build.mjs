// dsh-focus-island — build step for the Client half.
//
// The DSH loader serves ONE dynamic browser artifact (`lib/client.js`) whose
// factory is a plain function body. Multi-member parallel work is therefore
// authored as small ESM modules and concatenated here:
//
//   lib/core.js          pure focus state machine (no DOM)
//   lib/widget.js        the Dynamic Island visual (React, no DSH APIs)
//   lib/monitor-client.js  optional resource poller (fetch)
//   lib/client-main.js   DOM presence detection, layout tracking, slot wiring
//
// `export` modifiers are stripped because the concatenated body lives inside
// the loader factory. Run: `node build.mjs` (or `node build.mjs --check` to
// verify lib/client.js is current without writing).

import { readFile, writeFile } from 'node:fs/promises'

const BASE = new URL('./', import.meta.url)
const PARTS = ['core.js', 'notify.js', 'widget.js', 'monitor-client.js', 'client-main.js']
const TARGET = new URL('lib/client.js', BASE)

/** Remove ESM export syntax so the file can be concatenated into a function body. */
function stripExports(source) {
  return source
    .replace(/^export\s*\{[^}]*\}\s*;?\s*$/gm, '')
    .replace(/^export\s+default\s+/gm, '')
    .replace(/^export\s+(?=(?:async\s+)?(?:function|class|const|let|var)\b)/gm, '')
}

/** Read the four authored parts and return the single artifact text. */
async function render() {
  const chunks = []
  for (const part of PARTS) {
    let source
    try {
      source = await readFile(new URL(`lib/${part}`, BASE), 'utf8')
    } catch (error) {
      throw new Error(`cannot read lib/${part}: ${error instanceof Error ? error.message : String(error)}`)
    }
    chunks.push(`\n// ==================== lib/${part} ====================\n${stripExports(source).trimEnd()}\n`)
  }
  const header = `// dsh-focus-island — Client half (GENERATED by build.mjs from lib/core.js,
// lib/widget.js, lib/monitor-client.js and lib/client-main.js; do not edit).
//
// A frame-wide floating "focus island" registered into the official
// \`shell.overlay\` seat. It counts the time you spend passively watching —
// page visible and focused, composer empty, not typing, not sending — and warns
// you when a configured budget (10 min .. 4 h) is used up. Sending a message
// resets it; skipping needs an explicit second confirmation.
`
  return `${header}\nwindow.__ModuleLoader__.load({\n  id: 'dsh-focus-island',\n  factory: (require) => {\n    const React = require('react')\n    const h = React.createElement\n${chunks.join('')}  },\n})\n`
}

const text = await render()
const check = process.argv.includes('--check')

if (check) {
  const current = await readFile(TARGET, 'utf8').catch(() => '')
  if (current !== text) {
    console.error('lib/client.js is stale — run: node build.mjs')
    process.exit(1)
  }
  console.log('lib/client.js is up to date')
} else {
  await writeFile(TARGET, text)
  console.log(`wrote lib/client.js (${text.length} bytes)`)
}
