// dsh-focus-island — build step for the Client half.
//
// The DSH loader serves ONE dynamic browser artifact (`lib/client.js`) whose
// factory is a plain function body. Multi-member parallel work is therefore
// authored as small ESM modules and concatenated here:
//
//   lib/core.js          pure focus state machine (no DOM)
//   lib/notify.js        desktop notification + synthesised sound
//   lib/whale-atlas.js   embedded official whale atlas (generated, base64)
//   lib/whale.js         the official pixel whale renderer (strict mask)
//   lib/widget.js        the Dynamic Island visual (React, no DSH APIs)
//   lib/monitor-client.js  optional resource poller (fetch)
//   lib/client-main.js   DOM presence detection, layout tracking, slot wiring
//
// `export` modifiers are stripped because the concatenated body lives inside
// the loader factory, and so are the `import` lines that bind one part to
// another (they are all in scope once concatenated). Run: `node build.mjs`
// (or `node build.mjs --check` to verify lib/client.js is current without
// writing).

import { readFile, writeFile } from 'node:fs/promises'

const BASE = new URL('./', import.meta.url)
const PARTS = ['core.js', 'notify.js', 'whale-atlas.js', 'whale.js', 'widget.js', 'monitor-client.js', 'client-main.js']
const TARGET = new URL('lib/client.js', BASE)

/** Remove ESM export syntax so the file can be concatenated into a function body. */
function stripExports(source) {
  return source
    .replace(/^export\s*\{[^}]*\}\s*;?\s*$/gm, '')
    .replace(/^export\s+default\s+/gm, '')
    .replace(/^export\s+(?=(?:async\s+)?(?:function|class|const|let|var)\b)/gm, '')
}

/**
 * Drop the module-to-module imports.
 *
 * The parts are sibling modules during development (each verify script loads
 * one directly) and become plain declarations in one shared scope after the
 * concatenation. Only the parts' own relative imports are removed; a stray
 * `import` of a real package would still be a mistake and stays visible.
 */
function stripLocalImports(source) {
  return source.replace(/^import\s+\{[^}]*\}\s+from\s+'\.\/[^']+'\s*;?\s*$/gm, '')
}

/** Read the seven authored parts and return the single artifact text. */
async function render() {
  const chunks = []
  for (const part of PARTS) {
    let source
    try {
      source = await readFile(new URL(`lib/${part}`, BASE), 'utf8')
    } catch (error) {
      throw new Error(`cannot read lib/${part}: ${error instanceof Error ? error.message : String(error)}`)
    }
    chunks.push(`\n// ==================== lib/${part} ====================\n${stripLocalImports(stripExports(source)).trimEnd()}\n`)
  }
  const header = `// dsh-focus-island — Client half (GENERATED by build.mjs from the seven
// modules under lib/; do not edit).
//
// A frame-wide floating "focus island" registered into the official
// \`shell.overlay\` seat. It counts the time a conversation window stays visible
// and focused — typing, a draft and a running turn do not pause it — and warns
// you when a configured budget (5 min .. 3 h) is used up. Sending a message
// resets it; skipping needs an explicit second confirmation; strict mode covers
// the frame with the official pixel whale and the live per-session durations.
`
  return `${header}\nwindow.__ModuleLoader__.load({\n  id: 'dsh-focus-island',\n  factory: (require) => {\n    const React = require('react')\n    const h = React.createElement\n${chunks.join('')}  },\n})\n`
}

const text = await render()
const check = process.argv.includes('--check')

if (check) {
  const current = await readFile(TARGET, 'utf8').catch(() => '')
  if (current !== text) {
    console.error('lib/client.js is stale — run: node build.mjs')
    process.exit(1)
  }
  console.log('lib/client.js is up to date')
} else {
  await writeFile(TARGET, text)
  console.log(`wrote lib/client.js (${text.length} bytes)`)
}
