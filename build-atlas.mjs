// dsh-focus-island — generate the embedded whale atlas module.
//
// Why embed instead of loading `/plugins/<pkg>/assets/...`: the strict mask has
// to show the official pixel whale in every profile (web / headless / desktop)
// without depending on the plugin-asset route being mounted, and without a dsh
// restart. One base64 data URL inside the client bundle has neither failure
// mode, and it is still the official artwork byte for byte — this script only
// re-encodes lib/assets/breach-atlas.webp.
//
// Run: node build-atlas.mjs [--check]

import { readFile, writeFile } from 'node:fs/promises'

const BASE = new URL('./', import.meta.url)
const SOURCE = new URL('lib/assets/breach-atlas.webp', BASE)
const TARGET = new URL('lib/whale-atlas.js', BASE)

const bytes = await readFile(SOURCE)
const base64 = bytes.toString('base64')

const text = `/**
 * dsh-focus-island — the official pixel-whale frame atlas, embedded.
 *
 * GENERATED by build-atlas.mjs from lib/assets/breach-atlas.webp; do not edit.
 * Source: @deepseek-ai/dsh-client-ui-brand-official (MIT), the artwork the app
 * shows on a new conversation. Vendored unchanged: ${bytes.length} bytes,
 * 2304 x 1296 WebP, 137 frames of 192 x 108 in 12 columns.
 */

export const WHALE_ATLAS_URL = 'data:image/webp;base64,${base64}'
`

const check = process.argv.includes('--check')
if (check) {
  const current = await readFile(TARGET, 'utf8').catch(() => '')
  if (current !== text) {
    console.error('lib/whale-atlas.js is stale — run: node build-atlas.mjs')
    process.exit(1)
  }
  console.log('lib/whale-atlas.js is up to date')
} else {
  await writeFile(TARGET, text)
  console.log(`wrote lib/whale-atlas.js (${text.length} bytes from ${bytes.length} webp bytes)`)
}
